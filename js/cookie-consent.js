/* =============================================
   WeddingAI.video — Cookie Consent (GDPR/CCPA)
   Minimal banner. Persists in localStorage.
   - First visit: shows banner with Accept all / Essential only
   - Choice stored 180 days
   - Does not block rendering (deferred via defer attribute)

   I18N: the banner is built at runtime, so the middleware's server-side
   data-i18n pass cannot reach it - it only rewrites attributes inside the
   HTML. The strings therefore live in /i18n/cookie/<lang>.json (tiny
   standalone files, generated by scripts/build-cookie-i18n.py) and are
   fetched once, on first visit only. English is the fallback.

   The privacy link points at the LOCALIZED privacy page (/es/privacy/,
   /zh/privacy/, ...) because the middleware renders those; on the English
   site it is /privacy/.
   ============================================= */
(function () {
    'use strict';
    var KEY = 'wa_cookie_consent';

    var EN = {
        heading: '🍪 We use cookies',
        body: 'We use essential cookies to run this site and optional analytics cookies to understand how it performs. See our {link} for details.',
        link: 'privacy policy',
        essential: 'Essential only',
        accept: 'Accept all',
        label: 'Cookie consent'
    };

    function get() { try { return localStorage.getItem(KEY); } catch (e) { return null; } }
    function set(v) { try { localStorage.setItem(KEY, v); } catch (e) { /* private mode */ } }
    function dismiss(v) { set(v); var b = document.getElementById('wa-cookie-banner'); if (b) b.remove(); }

    // The language the middleware put on <html lang="...">. Falls back to
    // English for anything unknown.
    function currentLang() {
        var l = (document.documentElement && document.documentElement.lang || '').toLowerCase();
        return /^[a-z]{2}$/.test(l) ? l : 'en';
    }

    function privacyHref(lang) {
        return (lang && lang !== 'en') ? '/' + lang + '/privacy/' : '/privacy/';
    }

    function render(strings, lang) {
        if (document.getElementById('wa-cookie-banner')) return;
        var b = document.createElement('div');
        b.id = 'wa-cookie-banner';
        b.setAttribute('role', 'region');
        b.setAttribute('aria-label', strings.label);
        b.style.cssText = 'position:fixed;left:16px;right:16px;bottom:16px;z-index:9999;background:#2C2C2C;color:#fff;padding:1rem 1.25rem;border-radius:12px;box-shadow:0 8px 32px rgba(0,0,0,.25);display:flex;flex-wrap:wrap;align-items:center;gap:.75rem;font-size:.875rem;max-width:920px;margin:0 auto;';

        var href = privacyHref(lang);
        var link = '<a href="' + href + '" style="color:#D4AF37;text-decoration:underline;">' + strings.link + '</a>';
        var body = String(strings.body).replace('{link}', link);

        b.innerHTML =
            '<div style="flex:1 1 320px;line-height:1.5;"><strong style="display:block;margin-bottom:.25rem;">' + strings.heading + '</strong>' + body + '</div>' +
            '<div style="display:flex;gap:.5rem;flex-wrap:wrap;">' +
            '<button type="button" id="wa-cookie-reject" style="background:transparent;color:#fff;border:1px solid rgba(255,255,255,.4);padding:.5rem 1rem;border-radius:6px;cursor:pointer;font:inherit;">' + strings.essential + '</button>' +
            '<button type="button" id="wa-cookie-accept" style="background:#D4AF37;color:#2C2C2C;border:0;padding:.5rem 1rem;border-radius:6px;cursor:pointer;font:inherit;font-weight:600;">' + strings.accept + '</button>' +
            '</div>';
        document.body.appendChild(b);
        document.getElementById('wa-cookie-accept').addEventListener('click', function () { dismiss('all'); });
        document.getElementById('wa-cookie-reject').addEventListener('click', function () { dismiss('essential'); });
    }

    // Only the first visit needs the strings, so the fetch happens once.
    function loadStrings(lang) {
        if (lang === 'en') { render(EN, lang); return; }
        fetch('/i18n/cookie/' + lang + '.json', { credentials: 'same-origin' })
            .then(function (r) { return r.ok ? r.json() : null; })
            .then(function (data) { render(data || EN, lang); })
            .catch(function () { render(EN, lang); });
    }

    if (!get() && document.body) loadStrings(currentLang());
})();
