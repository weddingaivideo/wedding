#!/usr/bin/env python3
"""
Verify that the PDF pipeline can put pages of DIFFERENT sizes in one
document, and that the legacy single-size path still behaves exactly as
before (§2.17).

WHY THIS EXISTS
---------------
downloadPdfPages() had exactly one page size for the whole document
(opts.pageWidth / opts.pageHeight). The photo album is fine with that, but
a wedding stationery pack is not: an invitation is 5x7 in, a place card is
3.5x2 in and a poster is 18x24 in, and all three have to end up in one
file. So the function was split into buildPdfPages() (returns the document)
and downloadPdfPages() (builds it and saves it), and a page factory may now
return { canvas, pageWidth, pageHeight } to carry its own size.

Two jsPDF behaviours make this easy to get wrong, and both are MEASURED
here rather than assumed:

  1. jsPDF's orientation argument OVERRIDES the size array and SWAPS the
     two dimensions when they disagree - addPage([5,7],'landscape')
     really produces a 7x5 in page. So a landscape page that is handed to
     jsPDF as [5,7] with the orientation 'portrait' comes out rotated.
  2. The FIRST page's size comes from the constructor, not from addPage,
     so the constructor has to be told the first page's size.

The proof is the PDF itself: the script reads every /MediaBox out of the
generated bytes and compares it with the size that was asked for. A
checker that finds no MediaBox at all is a failure, never a pass.

Usage:  python scripts/verify-pdf-page-sizes.py
Exit code 0 = verified, 1 = failed.
"""

import base64
import http.server
import re
import socketserver
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORT = 8797

_headers = (ROOT / "_headers").read_text(encoding="utf-8")
_m = re.search(r"^\s*Content-Security-Policy:\s*(.+)$", _headers, re.M)
if not _m:
    raise SystemExit("[FAIL] no Content-Security-Policy in _headers")
NONCE = "weddingaiverifypdf"
CSP = re.sub(r"'nonce-[^']+'", f"'nonce-{NONCE}'", _m.group(1).strip())
CSP = CSP.replace("'wasm-unsafe-eval'",
                  f"'nonce-{NONCE}' 'wasm-unsafe-eval'")

SCRIPT_RE = re.compile(r"(<script\b)([^>]*)>", re.I)

# A synthetic page: the test needs a document that loads common.js and
# nothing else. It is served by the test server, not added to the repo.
TEST_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>pdf page size probe</title></head>
<body>
<h1>pdf page size probe</h1>
<script src="/js/tools/common.js"></script>
</body></html>
"""

MEDIABOX_RE = re.compile(
    rb"/MediaBox\s*\[\s*([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)\s+([\d.\-]+)\s*\]")


class Handler(http.server.SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=str(ROOT), **kw)

    def end_headers(self):
        self.send_header("Content-Security-Policy", CSP)
        self.send_header("Cache-Control", "no-store")
        super().end_headers()

    def do_GET(self):
        path = self.path.split("?")[0]
        if path == "/__pdf_page_size_test.html":
            body = TEST_PAGE.encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        target = ROOT / path.lstrip("/")
        if path.endswith("/"):
            target = target / "index.html"
        if target.exists() and target.is_file() and target.suffix == ".html":
            html = target.read_text(encoding="utf-8", errors="ignore")
            html = SCRIPT_RE.sub(
                lambda m: (m.group(1) + m.group(2) + f' nonce="{NONCE}"' + ">")
                if "nonce=" not in m.group(2) else m.group(0), html)
            html = html.replace("__CSP_NONCE__", NONCE)
            body = html.encode("utf-8")
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        return super().do_GET()

    def log_message(self, *a):
        pass


# Runs inside the page: builds a PDF from the given page specs and returns
# the raw bytes as base64. `spec` is
#   { unit, fallback: [w, h], pages: [ {pageWidth, pageHeight} | {} ] }
BUILD_JS = """(spec) => {
  function makeCanvas(w, h) {
    var c = document.createElement('canvas');
    c.width = w; c.height = h;
    var ctx = c.getContext('2d');
    ctx.fillStyle = '#fff';
    ctx.fillRect(0, 0, w, h);
    ctx.fillStyle = '#333';
    ctx.fillRect(0, 0, Math.max(1, Math.round(w / 4)), Math.max(1, Math.round(h / 4)));
    return c;
  }
  var makers = spec.pages.map(function (s) {
    return function () {
      var c = makeCanvas(s.px || 200, s.py || 200);
      if (s.pageWidth) {
        return { canvas: c, pageWidth: s.pageWidth, pageHeight: s.pageHeight };
      }
      return c;
    };
  });
  return window.weddingAITool.buildPdfPages(makers, {
    unit: spec.unit || 'in',
    pageWidth: spec.fallback ? spec.fallback[0] : undefined,
    pageHeight: spec.fallback ? spec.fallback[1] : undefined
  }).then(function (doc) {
    var bytes = new Uint8Array(doc.output('arraybuffer'));
    var bin = '';
    var chunk = 0x8000;
    for (var i = 0; i < bytes.length; i += chunk) {
      bin += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
    }
    return btoa(bin);
  });
}"""

# The OLD algorithm, inlined. It is the falsifiable control: it can only
# ever produce ONE size for the whole document, so a document with mixed
# sizes must come out identical in every page - which is exactly what the
# new function must NOT do.
OLD_BUILD_JS = """(spec) => {
  function makeCanvas(w, h) {
    var c = document.createElement('canvas');
    c.width = w; c.height = h;
    var ctx = c.getContext('2d');
    ctx.fillStyle = '#fff';
    ctx.fillRect(0, 0, w, h);
    return c;
  }
  return window.weddingAITool.loadVendor('jspdf').then(function (ns) {
    var Ctor = (ns && ns.jsPDF) || (window.jspdf && window.jspdf.jsPDF);
    var pdf = null;
    var chain = Promise.resolve();
    spec.pages.forEach(function (s) {
      chain = chain.then(function () {
        var canvas = makeCanvas(200, 200);
        var pw = spec.fallback ? spec.fallback[0] : canvas.width;
        var ph = spec.fallback ? spec.fallback[1] : canvas.height;
        var landscape = pw > ph;
        if (!pdf) {
          pdf = new Ctor({ orientation: landscape ? 'landscape' : 'portrait',
                           unit: spec.unit || 'in', format: [pw, ph], compress: true });
        } else {
          pdf.addPage([pw, ph], landscape ? 'landscape' : 'portrait');
        }
        pdf.addImage(canvas.toDataURL('image/jpeg', 0.92), 'JPEG', 0, 0, pw, ph, undefined, 'FAST');
      });
    });
    return chain.then(function () {
      var bytes = new Uint8Array(pdf.output('arraybuffer'));
      var bin = '';
      var chunk = 0x8000;
      for (var i = 0; i < bytes.length; i += chunk) {
        bin += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
      }
      return btoa(bin);
    });
  });
}"""


def media_boxes(pdf_bytes):
    """Every page size in the document, in PDF points."""
    out = []
    for m in MEDIABOX_RE.finditer(pdf_bytes):
        x1, y1, x2, y2 = (float(m.group(i)) for i in (1, 2, 3, 4))
        out.append((round(x2 - x1, 2), round(y2 - y1, 2)))
    return out


def pt(w_in, h_in):
    """Inches to PDF points (72 per inch)."""
    return (round(w_in * 72, 2), round(h_in * 72, 2))


def main():
    from playwright.sync_api import sync_playwright

    httpd = socketserver.TCPServer(("127.0.0.1", PORT), Handler)
    httpd.allow_reuse_address = True
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    time.sleep(0.6)
    print("serving on http://127.0.0.1:%d with the live CSP" % PORT)

    failures = []
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch()
            page = browser.new_page()
            errors = []
            page.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
            page.on("console",
                    lambda m: errors.append(m.text) if m.type == "error" else None)
            page.goto("http://127.0.0.1:%d/__pdf_page_size_test.html" % PORT,
                      wait_until="load", timeout=60000)
            page.wait_for_timeout(500)
            if not page.evaluate(
                    "() => !!(window.weddingAITool && window.weddingAITool.buildPdfPages)"):
                failures.append("common.js did not load - buildPdfPages is missing")
                browser.close()
                print("RESULT: FAIL")
                for f in failures:
                    print("  - " + f)
                return 1

            def build(spec, old=False):
                b64 = page.evaluate(OLD_BUILD_JS if old else BUILD_JS, spec)
                return base64.b64decode(b64)

            # ---- 1. mixed sizes in one document --------------------------
            mixed_pages = [
                {"pageWidth": 5, "pageHeight": 7},      # invitation
                {"pageWidth": 3.5, "pageHeight": 2},    # place card
                {"pageWidth": 8, "pageHeight": 8},      # square album page
                {"pageWidth": 7, "pageHeight": 5},      # landscape
            ]
            boxes = media_boxes(build({"unit": "in", "pages": mixed_pages}))
            expected = [pt(5, 7), pt(3.5, 2), pt(8, 8), pt(7, 5)]
            print("mixed-size document, page sizes in points:")
            for i, b in enumerate(boxes):
                print("   page %d: %s x %s pt" % (i + 1, b[0], b[1]))
            if len(boxes) != len(mixed_pages):
                failures.append("the document has %d pages, expected %d"
                                % (len(boxes), len(mixed_pages)))
            elif boxes != expected:
                failures.append("the page sizes are %r, expected %r" % (boxes, expected))

            # ---- 2. the old algorithm CANNOT do this ----------------------
            # The control gets the same fallback size the album uses, so the
            # only difference between the two documents is the per-page size.
            old_boxes = media_boxes(
                build({"unit": "in", "pages": mixed_pages, "fallback": [8, 8]},
                      old=True))
            print("the old single-size algorithm would produce: %r" % (old_boxes,))
            if old_boxes and len(set(old_boxes)) != 1:
                failures.append("the control did not behave like the old code - "
                                "the comparison proves nothing")
            if boxes == old_boxes:
                failures.append("the new pipeline produces the same pages as the "
                                "old one - the per-page size does nothing")

            # ---- 3. the legacy path is unchanged --------------------------
            legacy_pages = [{}, {}, {}]
            lb = media_boxes(build({"unit": "in", "pages": legacy_pages,
                                     "fallback": [8, 8]}))
            print("legacy path (one size for the whole book): %r" % (lb,))
            if lb != [pt(8, 8)] * 3:
                failures.append("the legacy single-size path changed: %r" % (lb,))

            # ---- 4. a page without its own size falls back -----------------
            partial_pages = [{"pageWidth": 5, "pageHeight": 7},
                             {},
                             {"pageWidth": 3.5, "pageHeight": 2}]
            pb = media_boxes(build({"unit": "in", "pages": partial_pages,
                                     "fallback": [8, 8]}))
            print("mixed with one fallback page: %r" % (pb,))
            want = [pt(5, 7), pt(8, 8), pt(3.5, 2)]
            if pb != want:
                failures.append("the fallback page is %r, expected %r" % (pb, want))

            # ---- 5. the download path still produces a file ----------------
            try:
                with page.expect_download(timeout=20000) as dl:
                    page.evaluate("""() => {
                      var makers = [function () {
                        var c = document.createElement('canvas');
                        c.width = 240; c.height = 240;
                        var ctx = c.getContext('2d');
                        ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, 240, 240);
                        ctx.fillStyle = '#222'; ctx.fillRect(10, 10, 120, 120);
                        return c;
                      }];
                      return window.weddingAITool.downloadPdfPages(
                        makers, 'weddingai.pdf', { unit: 'in', pageWidth: 8, pageHeight: 8 });
                    }""")
                download = dl.value
                path = download.path()
                size = Path(path).stat().st_size if path else 0
                with open(path, "rb") as fh:
                    head = fh.read(5)
                if head != b"%PDF-":
                    failures.append("the downloaded file is not a PDF: %r" % head)
                elif size < 1000:
                    failures.append("the downloaded PDF is only %d bytes" % size)
                else:
                    print("the download path produced a %d byte PDF" % size)
            except Exception as exc:  # noqa: BLE001 - reported, not raised
                failures.append("the download path failed: %s" % exc)

            for e in errors[:6]:
                print("  console error:", e[:200])
            for e in [e for e in errors if "Content Security Policy" in e or "Refused to" in e]:
                failures.append("CSP violation: " + e[:200])
            browser.close()
    finally:
        httpd.shutdown()

    print()
    if failures:
        print("RESULT: FAIL")
        for f in failures:
            print("  - " + f)
        return 1
    print("RESULT: OK - mixed page sizes work and the legacy path is unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
