"""
Insert a "Blog" link into the main nav of every HTML file.

Idempotent: skips files that already have a /blog/ nav link.
Also normalizes the form: <li><a href="..." title="...">Blog</a></li>
right between Gallery and About (matching the order used in the freshly
generated blog pages).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

NEW_LINK = '<li><a href="/blog/" title="Read our wedding video blog">Blog</a></li>'

# Match a nav block: a <ul class="nav-list"> ... </ul> inside <nav class="main-nav">
NAV_UL = re.compile(
    r'(<ul class="nav-list">)(.*?)(</ul>)',
    re.DOTALL,
)


def inject(html: str) -> tuple[str, bool]:
    """Return (new_html, changed)."""
    # Skip if already has /blog/ in nav
    if 'href="/blog/"' in html[: html.find("</nav>") if "</nav>" in html else len(html)]:
        # crude: check the FIRST nav block only
        m = NAV_UL.search(html)
        if m and "/blog/" in m.group(0):
            return html, False

    m = NAV_UL.search(html)
    if not m:
        return html, False

    # We want to insert Blog right after the Gallery link, before the About link.
    inner = m.group(2)
    # The pattern: <li><a href="...gallery..." ...>Gallery</a></li>
    gallery_li = re.search(
        r'(<li><a href="[^"]*gallery[^"]*"[^>]*>Gallery</a></li>)',
        inner,
        re.IGNORECASE,
    )
    if gallery_li:
        new_inner = (
            inner[: gallery_li.end()]
            + "\n                    "
            + NEW_LINK
            + inner[gallery_li.end() :]
        )
    else:
        # Fallback: just append at the end of the list (before any btn-nav)
        btn = re.search(r'(<li><a [^>]*class="btn-nav")', inner)
        if btn:
            new_inner = inner[: btn.start()] + NEW_LINK + "\n                    " + inner[btn.start() :]
        else:
            new_inner = inner + "\n                    " + NEW_LINK

    return html[: m.start(2)] + new_inner + html[m.end(2) :], True


def main() -> int:
    n = 0
    n_skipped = 0
    for f in ROOT.rglob("*.html"):
        # Skip files inside /blog/ (already have Blog link, generated by generate-blog.py)
        rel = f.relative_to(ROOT)
        if rel.parts[0] == "blog":
            continue
        # Skip verification file
        if f.name == "google-site-verification.html":
            continue
        try:
            text = f.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if "main-nav" not in text:
            continue
        new_text, changed = inject(text)
        if changed:
            f.write_text(new_text, encoding="utf-8")
            print(f"[+] {rel}")
            n += 1
        else:
            n_skipped += 1
    print(f"\nDone. {n} files updated, {n_skipped} already had Blog link.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
