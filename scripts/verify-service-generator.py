#!/usr/bin/env python3
"""
verify-service-generator.py — diff-check that the rendered service-card HTML
in the deployed pages matches what `generate-service-category-indexes.py` would
emit today.

Why: the service pages (services/index.html, services/absence-compensation/index.html,
and the sub-card blocks inside services/<category>/<feature>/index.html) are partly
generated by `generate-service-category-indexes.py` and partly hand-edited. If
someone re-runs the generator after a hand-edit, the generator silently overwrites
the hand-edit because it doesn't know about it.

This script catches that drift: it re-renders every service card via the
generator's `service_card()` function and compares the media block
(<picture>/<video>) to what's actually on disk in the deployed pages. If
they differ, either the page is stale (regen needed) or the generator is stale
(generator needs the new hand-edit folded in).

Usage:
    python scripts/verify-service-generator.py
    python scripts/verify-service-generator.py --group absence-compensation
    python scripts/verify-service-generator.py --verbose   # show first 300 chars of drift

Exit code: 0 if all match, 1 if any drift.
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load_generator():
    spec = importlib.util.spec_from_file_location(
        "gen", str(ROOT / "scripts" / "generate-service-category-indexes.py")
    )
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    return gen


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--group", help="Only check one group slug, e.g. absence-compensation")
    p.add_argument("--verbose", action="store_true", help="Show first 300 chars of any drift")
    args = p.parse_args()

    gen = load_generator()

    # Pages whose service-sub-card blocks must match what the generator emits:
    #   - The 3 hand-edited service pages
    #   - The 2 auto-generated category-index pages (the generator overwrites
    #     them on every run, so checking them here gives us a quick "data and
    #     output are in sync" smoke test — re-run the generator and re-run
    #     this script after any change to GROUPS / service_card()).
    pages = [
        ROOT / "services" / "absence-compensation" / "family-tribute" / "index.html",
        ROOT / "services" / "absence-compensation" / "index.html",
        ROOT / "services" / "index.html",
        ROOT / "services" / "personalization" / "index.html",
        ROOT / "services" / "video-enhancement" / "index.html",
    ]

    groups = gen.GROUPS
    if args.group:
        if args.group not in groups:
            print(f"Unknown group: {args.group}. Available: {', '.join(groups.keys())}", file=sys.stderr)
            return 1
        groups = {args.group: groups[args.group]}

    total_checks = 0
    drifts = 0

    for group_slug, group in groups.items():
        for svc in group["children"]:
            rendered = gen.service_card(svc)
            rendered_media = re.search(r"<(picture|video)\b[^>]*>.*?</\1>", rendered, re.DOTALL)
            if not rendered_media:
                continue
            for page in pages:
                if not page.exists():
                    continue
                text = page.read_text(encoding="utf-8")
                idx = text.find(f">{svc['title']}<")
                if idx < 0:
                    # Title not in this page (e.g. absence-compensation sub-pages
                    # show the feature cards, not the service-sub-cards)
                    continue
                # Pin `start` to the service-sub-card opening div, not any div.
                # The previous `<div ` rfind matched the header/footer/nav-dropdown
                # wrapper for titles that ALSO appear in the nav menu — e.g. on
                # /services/absence-compensation/ the "Vintage Restoration" nav
                # link is the first hit for that title, but the actual service
                # card is in the (different) video-enhancement group. A loose
                # rfind grabbed `<div class="container header-inner">` and the
                # verifier reported a false-positive drift on every run.
                start = text.rfind('<div class="service-sub-card">', 0, idx)
                if start < 0:
                    # Title is in this page but not as a service-sub-card
                    # (it's the nav link, footer link, breadcrumb, etc.).
                    # Skip — it's not a card to compare.
                    continue
                end = text.find("</div>", idx) + len("</div>")
                actual = text[start:end]
                actual_media = re.search(r"<(picture|video)\b[^>]*>.*?</\1>", actual, re.DOTALL)
                if not actual_media:
                    continue
                total_checks += 1
                if actual_media.group(0) == rendered_media.group(0):
                    continue
                drifts += 1
                page_label = page.parent.relative_to(ROOT)
                print(f"DRIFT [{page_label}] {svc['title']!r} ({group_slug})")
                if args.verbose:
                    print(f"  actual:    {actual_media.group(0)[:300]!r}")
                    print(f"  generated: {rendered_media.group(0)[:300]!r}")

    print(f"\nChecked {total_checks} service-card <media> blocks; {drifts} drift(s).")
    return 0 if drifts == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
